package com.example.util

enum class AppLanguage(val code: String, val displayName: String, val flag: String) {
    TURKISH("tr", "Türkçe", "🇹🇷"),
    ENGLISH("en", "English", "🇺🇸"),
    SPANISH("es", "Español", "🇪🇸"),
    CHINESE("zh", "中文 (简体)", "🇨🇳"),
    HINDI("hi", "हिन्दी", "🇮🇳");

    companion object {
        fun fromCode(code: String): AppLanguage =
            values().firstOrNull { it.code.equals(code, ignoreCase = true) } ?: TURKISH
    }
}

